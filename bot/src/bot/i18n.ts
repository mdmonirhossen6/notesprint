const DICTIONARIES: Record<Lang, Record<TranslationKey, string>> = { en, bn };

export type TranslationParams = Record<string, string | number>;

export function translate(lang: Lang, key: TranslationKey, params?: TranslationParams): string {
  const template = DICTIONARIES[lang][key] ?? en[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

export function translationKeys(): TranslationKey[] {
  return Object.keys(en) as TranslationKey[];
}

export function dictionaryFor(lang: Lang): Record<TranslationKey, string> {
  return DICTIONARIES[lang];
}

export function resolveTelegramLanguage(languageCode?: string | null): Lang {
  const code = languageCode?.trim().toLowerCase() ?? '';
  if (code.startsWith('bn')) return 'bn';
  if (code.startsWith('en')) return 'en';
  return 'bn';
}

export function languageLabel(lang: Lang): string {
  return lang === 'bn' ? 'বাংলা' : 'English';
}

export interface LanguageStore {
  resolve(userId: number, languageCode?: string | null): Lang;
  get(userId: number): Lang | null;
  set(userId: number, lang: Lang): void;
  clear(userId: number): void;
  prune(): number;
  size(): number;
}

export interface LanguageStoreOptions {
  ttlMs: number;
  now?: () => number;
}

export interface StoredLanguage {
  lang: Lang;
  updatedAt: number;
}

export function createLanguageStore(options: LanguageStoreOptions): LanguageStore {
  const now = options.now ?? Date.now;
  const entries = new Map<number, StoredLanguage>();

  const get = (userId: number): Lang | null => {
    const entry = entries.get(userId);
    if (!entry) return null;
    if (now() - entry.updatedAt > options.ttlMs) {
      entries.delete(userId);
      return null;
    }
    return entry.lang;
  };

  return {
    resolve(userId, languageCode) {
      const stored = get(userId);
      if (stored) {
        entries.get(userId)!.updatedAt = now();
        return stored;
      }
      const inferred = resolveTelegramLanguage(languageCode);
      entries.set(userId, { lang: inferred, updatedAt: now() });
      return inferred;
    },
    get,
    set(userId, lang) {
      entries.set(userId, { lang, updatedAt: now() });
    },
    clear(userId) {
      entries.delete(userId);
    },
    prune() {
      const current = now();
      let removed = 0;
      for (const [userId, entry] of entries) {
        if (current - entry.updatedAt > options.ttlMs) {
          entries.delete(userId);
          removed += 1;
        }
      }
      return removed;
    },
    size() {
      return entries.size;
    },
  };
}

