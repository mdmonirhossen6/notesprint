export function fileErrorMessage(
  lang: Lang,
  error: unknown,
  limits: { maxUploadMb: number; maxOutputMb: number },
): string {
  if (!(error instanceof FileHandlingError)) {
    return translate(lang, 'err.generic');
  }
  const key = FILE_ERROR_KEYS[error.code];
  if (!key) return translate(lang, 'err.generic');
  if (key === 'err.tooLarge') {
    return translate(lang, key, { max: limits.maxUploadMb });
  }
  if (key === 'err.outputTooLarge') {
    return translate(lang, key, { max: limits.maxOutputMb });
  }
  return translate(lang, key);
}

export function formatDuration(lang: Lang, milliseconds: number): string {
  const seconds = Math.max(1, Math.round(milliseconds / 1000));
  if (seconds < 60) return translate(lang, 'duration.seconds', { count: seconds });
  const minutes = Math.round(seconds / 60);
  if (minutes < 60) return translate(lang, 'duration.minutes', { count: minutes });
  const hours = Math.round(minutes / 60);
  return translate(lang, 'duration.hours', { count: hours });
}
